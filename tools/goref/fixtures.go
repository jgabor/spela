// fixtureWriter builds every case under work and copies the cases to out.
type fixtureWriter struct {
	repo   string
	work   string
	out    string
	cases  []*fixtureCase
	readme []readmeLine
}

// readmeLine is one entry of tests/fixtures/go/README.md.
type readmeLine struct {
	Path   string
	Covers string
	Writer string
}

func (w *fixtureWriter) note(path, covers, writer string) {
	w.readme = append(w.readme, readmeLine{Path: path, Covers: covers, Writer: writer})
}

func uintText(value uint64) string { return strconv.FormatUint(value, 10) }

func runFixtures(arguments []string) error {
	flags := flag.NewFlagSet("fixtures", flag.ContinueOnError)
	out := flags.String("out", filepath.Join("tests", "fixtures", "go"), "output folder")
	if err := flags.Parse(arguments); err != nil {
		return err
	}
	repo, err := os.Getwd()
	if err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(repo, "data", "manifest.json")); err != nil {
		return fmt.Errorf("run goref from the repository root: %w", err)
	}
	outDir, err := filepath.Abs(*out)
	if err != nil {
		return err
	}
	work, err := os.MkdirTemp(guardRoot, "work-")
	if err != nil {
		return err
	}
	w := &fixtureWriter{repo: repo, work: work, out: outDir}

	steps := []struct {
		name string
		run  func() error
	}{
		{"config", w.writeConfigCases},
		{"profiles", w.writeProfileCases},
		{"lists", w.writeListCases},
		{"games", w.writeGameCases},
		{"backups", w.writeBackupCases},
		{"caches", w.writeCacheCases},
		{"e2e library", w.writeE2ELibrary},
		{"sandboxes", w.writeSandboxes},
	}
	for _, step := range steps {
		if err := step.run(); err != nil {
			return fmt.Errorf("%s: %w", step.name, err)
		}
	}

	// Replace only the case folders goref owns, so transcripts and anything
	// else in the output folder stay.
	for _, c := range w.cases {
		target := filepath.Join(outDir, filepath.FromSlash(c.Name))
		if err := os.RemoveAll(target); err != nil {
			return err
		}
	}
	for _, c := range w.cases {
		target := filepath.Join(outDir, filepath.FromSlash(c.Name))
		if err := copyRelocated(c.Dir, target, c.Dir, FixtureRoot); err != nil {
			return fmt.Errorf("copy %s: %w", c.Name, err)
		}
		if err := rehashBackups(target); err != nil {
			return fmt.Errorf("rehash %s: %w", c.Name, err)
		}
	}
	if err := w.writeReadme(); err != nil {
		return err
	}
	fmt.Printf("wrote %d fixture cases to %s\n", len(w.cases), outDir)
	return nil
}

func (w *fixtureWriter) writeReadme() error {
	var builder strings.Builder
	builder.WriteString(readmeHeader)
	lines := slices.Clone(w.readme)
	slices.SortStableFunc(lines, func(left, right readmeLine) int { return strings.Compare(left.Path, right.Path) })
	builder.WriteString("| Path | What it covers | Written by |\n|---|---|---|\n")
	for _, line := range lines {
		fmt.Fprintf(&builder, "| `%s` | %s | %s |\n", line.Path, line.Covers, line.Writer)
	}
	builder.WriteString(readmeFooter)
	return writeText(filepath.Join(w.out, "README.md"), builder.String())
}

const readmeHeader = `# Go reference fixtures

These files were written by the Go version of spela, through its own code, so
the Rust migration and parity tests can check against what Go really wrote.
They are generated by ` + "`tools/goref`" + `. Do not edit them by hand; change the
generator and run it again:

` + "```bash" + `
GOPROXY=off GOFLAGS=-mod=mod go run ./tools/goref fixtures
` + "```" + `

## Layout

Each case is a folder that mirrors the XDG homes Go wrote into:

- ` + "`config/spela/`" + ` is ` + "`$XDG_CONFIG_HOME/spela`" + `: config.yaml, profiles/, lists/.
- ` + "`data/spela/`" + ` is ` + "`$XDG_DATA_HOME/spela`" + `: games.yaml, backups/.
- ` + "`cache/spela/`" + ` is ` + "`$XDG_CACHE_HOME/spela`" + `: manifest.json, update-check.json.
- ` + "`home/`" + ` is ` + "`$HOME`" + `, used by the sandboxes for the fixture Steam install.
- ` + "`library/`" + ` folders hold fixture game files and Steam libraries.
- ` + "`oracle.json`" + ` (where present) is what Go made of the case when it read it
  back: effective values, origins, load errors. It is not a Go file; goref
  wrote it from Go's return values.

## Paths

Go writes absolute paths. Every text file here has the case folder replaced by
the token ` + "`/fixture-root`" + `. A test copies a case into a temp folder and
replaces ` + "`/fixture-root`" + ` with that folder in every text file before use.

The sha256 in a backup file name such as ` + "`<sha256>-nvngx_dlss.dll`" + ` is the
hash Go computes over the original path. goref renames these files after the
copy so the hash is taken over the path under ` + "`/fixture-root`" + `, as if Go had
run there; that keeps the names stable between runs. After a test relocates a
case the names no longer match a fresh hash. Go never recomputes the name of
an existing entry (restore uses the recorded ` + "`backup_path`" + `), so tests must not
either.

## Times

Times that a caller can choose are pinned to 2026-10-26T17:02:10.123456789+02:00
(a deliberate non-UTC offset). Go always stamps ` + "`games.yaml`" + ` ` + "`updated_at`" + `
and the manifest cache ` + "`fetched_at`" + ` with the clock, so those change on each
run.

## Fictional games

Fixture games and app ids are fictional (9100010 to 9100499), decision 43. Where
a Go test or the Go e2e harness pins a real game, the case keeps the test's
shape with a fictional name and id. Real ids appear only where they come from
Go's built-in deny list, because a check against that list needs one of its
entries.

## Files

`

